GLYPH_W = 5
GLYPH_H = 7


def text_width(text, scale=1, spacing=1):
    """How wide a string will be once drawn, in pixels."""
    if not text:
        return 0
    return (len(text) * (GLYPH_W + spacing) - spacing) * scale


def draw_text(put, text, x, y, scale=1, spacing=1):
    """Draw `text` by calling put(px, py) for every lit pixel.

    Passing a callback rather than an image keeps this independent of how the
    caller stores pixels -- the same routine writes into a DDS buffer or a
    preview, and neither needs to know about the other.
    """
    cursor = x
    for ch in text.upper():
        glyph = GLYPHS.get(ch, GLYPHS[' '])
        for row_index, row in enumerate(glyph):
            for col_index, cell in enumerate(row):
                if cell == '1':
                    for sy in range(scale):
                        for sx in range(scale):
                            put(cursor + col_index * scale + sx,
                                y + row_index * scale + sy)
        cursor += (GLYPH_W + spacing) * scale
